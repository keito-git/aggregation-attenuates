"""
Generate the verbatim prompt appendix directly from the prompt constants of the generation scripts
(generation/). Nothing is retyped: each template is read with ast.literal_eval and written inside a Verbatim block (fvextra, breaklines=true; the paper preamble must load fvextra).
Output: appendix_prompts_body.tex (body only; the section heading and the explanatory sentences live in the
manuscript).
Usage: python3 analysis/make_prompts_appendix.py [out_file]   (default: OUT_DIR/appendix_prompts_body.tex)
"""
import ast
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "generation"
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(os.environ.get("OUT_DIR", ROOT / "output")) / "appendix_prompts_body.tex"

# (file, constant, label shown in the appendix)
ITEMS = [
    ("goe_independent.py", "PLAIN_PROMPT", "GoEmotions, plain-listing (independent samples)"),
    ("goe_independent.py", "COT_PROMPT", "GoEmotions, SC / CoT (independent samples)"),
    ("goe_independent.py", "YESNO_PROMPT", "GoEmotions, Yes/No format (factorial design)"),
    ("goe_debate.py", "INIT_TMPL", "GoEmotions, debate, first round"),
    ("goe_debate.py", "DEBATE_TMPL", "GoEmotions, debate, later rounds"),
    ("goe_moa.py", "PROPOSE_TMPL", "GoEmotions, MoA, proposer layer"),
    ("goe_moa.py", "SYNTH_TMPL", "GoEmotions, MoA, synthesis layers"),
    ("goe_ccd.py", "CLASSIFY_TMPL", "GoEmotions, zero-shot and CCD, per-label Yes/No classification"),
    ("goe_ccd.py", "PROPOSER_TMPL", "GoEmotions, CCD, context proposer"),
    ("goe_ccd.py", "CLASSIFY_CTX_TMPL", "GoEmotions, CCD, context-conditioned classification"),
    ("goe_clarification.py", "CLARIFY_TMPL", "GoEmotions, clarification ensembling, clarification generation"),
    ("goe_clarification.py", "CLASSIFY_CLAR_TMPL", "GoEmotions, clarification ensembling, conditioned classification"),
    ("lewidi_independent.py", "INDEP_PROMPT", "LeWiDi-MP, independent samples"),
    ("lewidi_debate.py", "INIT", "LeWiDi-MP, debate, first round"),
    ("lewidi_debate.py", "DEBATE", "LeWiDi-MP, debate, later rounds"),
    ("lewidi_moa.py", "PROPOSE", "LeWiDi-MP, MoA, proposer layer"),
    ("lewidi_moa.py", "SYNTH", "LeWiDi-MP, MoA, synthesis layers"),
]


def constant(path, name):
    for node in ast.parse(path.read_text()).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise KeyError(f"{name} not found in {path.name}")


parts = ["% AUTO-GENERATED by make_prompts_appendix.py from the scripts that produced the results"]
for fname, name, label in ITEMS:
    text = constant(SRC / fname, name)
    parts.append(f"\\paragraph{{{label}}}")
    parts.append("\\begin{Verbatim}[breaklines=true,fontsize=\\small]")
    parts.append(text.rstrip("\n"))
    parts.append("\\end{Verbatim}")
# how peer answers are inserted (read from the code, quoted as code)
parts.append("\\paragraph{Insertion of peer answers}")
parts.append("\\begin{Verbatim}[breaklines=true,fontsize=\\small]")
parts.append("debate: others    = '\\n\\n'.join(f\"Agent {j+1}'s answer:\\n{answer_j}\" for every other agent j)")
parts.append("MoA:    responses = '\\n\\n'.join(f'Agent {j+1}:\\n{answer_j}' for all K agents j)")
parts.append("\\end{Verbatim}")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(parts) + "\n")
print(f"wrote {OUT} ({len(ITEMS)} templates)")
